def part1_deduplicate_road_points():
    """
    (1) Deduplicate road scoring points to one point per 250 m of road.
    Report total length scored and points per km for each segment.
    """
    import geopandas as gpd
    from shapely.geometry import Point

    print("=" * 70)
    print("PART 1: Road Geometry & Scoring Point Deduplication")
    print("=" * 70)

    # Load 18 backend segments
    bseg = S.load_backend_segments(None)
    verts = [(bseg.start_lat[0], bseg.start_lng[0])] + list(zip(bseg.end_lat, bseg.end_lng))
    proj = B.Proj(float(np.mean([v[0] for v in verts])))
    route_xy = proj.xy([v[0] for v in verts], [v[1] for v in verts])
    _, _, _, coarse_len = B.project_to_polyline(route_xy[:1], route_xy)
    cum_coarse = np.concatenate([[0.0], np.cumsum(np.hypot(*np.diff(route_xy, axis=0).T))])

    # Raw points from score_segments.py (from 206 OSM ways)
    raw_pts_xy, raw_how = S.road_points(proj, route_xy, 0.0, coarse_len, 0.25)
    _, _, along_raw, _ = B.project_to_polyline(raw_pts_xy, route_xy)
    raw_seg_idx = np.clip(np.searchsorted(cum_coarse[1:], along_raw, side="left"), 0, len(bseg) - 1)
    raw_counts = pd.Series(raw_seg_idx).value_counts().to_dict()

    # Load the true 247 km highway geometry
    gdf_hw = gpd.read_file(GEOJSON_ROUTE).to_crs(epsg=32644)
    highway = gdf_hw.geometry.iloc[0]
    total_highway_len_km = highway.length / 1000.0

    # Project the 18 segment bounds onto the continuous highway
    seg_bounds = []
    for i, row in bseg.iterrows():
        p_start = gpd.GeoSeries([Point(row["start_lng"], row["start_lat"])], crs="EPSG:4326").to_crs(epsg=32644).iloc[0]
        p_end = gpd.GeoSeries([Point(row["end_lng"], row["end_lat"])], crs="EPSG:4326").to_crs(epsg=32644).iloc[0]
        d_s = 0.0 if i == 0 else highway.project(p_start) / 1000.0
        d_e = total_highway_len_km if i == len(bseg) - 1 else highway.project(p_end) / 1000.0
        seg_bounds.append((row["id"], row["name"], d_s, d_e, d_e - d_s))

    # Deduplicate: sample strictly 1 point per 250 m along the actual centerline
    step_m = 250.0
    distances_m = np.arange(0, highway.length, step_m)
    pts_geom = [highway.interpolate(d) for d in distances_m]
    pts_chainage_km = distances_m / 1000.0
    total_dedup_points = len(pts_geom)
    total_scored_len_km = total_highway_len_km

    # Convert deduplicated points to WGS84 coordinates for terrain extraction
    pts_wgs84 = gpd.GeoSeries(pts_geom, crs="EPSG:32644").to_crs(epsg=4326)
    dedup_df = pd.DataFrame({
        "point_id": np.arange(total_dedup_points),
        "chainage_km": pts_chainage_km,
        "latitude": pts_wgs84.y,
        "longitude": pts_wgs84.x,
    })

    # Segment mapping
    seg_rows = []
    seg_point_indices = {}
    for i, (cid, name, ds, de, length) in enumerate(seg_bounds):
        in_seg = (pts_chainage_km >= ds) & (pts_chainage_km < de if de < total_highway_len_km else pts_chainage_km <= de)
        n_dedup = int(in_seg.sum())
        n_raw = raw_counts.get(i, 0)
        pts_per_km_dedup = n_dedup / length if length > 0 else 0.0
        pts_per_km_raw = n_raw / length if length > 0 else 0.0
        seg_point_indices[cid] = np.where(in_seg)[0]
        seg_rows.append({
            "id": cid,
            "name": name,
            "start_km": ds,
            "end_km": de,
            "length_km": length,
            "raw_points": n_raw,
            "raw_pts_per_km": pts_per_km_raw,
            "dedup_points": n_dedup,
            "dedup_pts_per_km": pts_per_km_dedup,
        })

    seg_table = pd.DataFrame(seg_rows)
    print(f"Total highway route length: {total_highway_len_km:.2f} km (expected ~247 km)")
    print(f"Raw scoring points from OSM ways: {len(raw_pts_xy)} points (heavily oversampled)")
    print(f"Deduplicated points (1 per 250 m): {total_dedup_points} points")
    print(f"Average points per km (deduplicated): {total_dedup_points / total_highway_len_km:.2f} pts/km\n")

    return {
        "total_highway_len_km": total_highway_len_km,
        "total_dedup_points": total_dedup_points,
        "total_raw_points": len(raw_pts_xy),
        "seg_table": seg_table,
        "dedup_df": dedup_df,
        "seg_bounds": seg_bounds,
        "seg_point_indices": seg_point_indices,
    }


def part2_oof_terrain_scores_and_correlation(part1_res):
    """
    (2) Compute out-of-fold terrain scores using the existing spatial blocks and buffer,
    aggregate to the 18 segments with the 90th percentile, and report the Spearman correlation
    against observed landslides per km from the 309 inventory, plus where seg_08 and seg_09 land.
    """
    import geopandas as gpd
    from shapely.geometry import Point

    print("=" * 70)
    print("PART 2: Out-of-Fold Terrain Scoring & Landslide Correlation")
    print("=" * 70)

    # 1. Load training dataset v2
    df_train = pd.read_csv(TRAIN_DATA_V2)
    along_train = df_train["along_km"].to_numpy()
    y_train = df_train["label"].to_numpy()
    X_train = df_train[DEM_FEATURES].to_numpy(float)

    # 2. Fit 6 leave-one-block-out models with 2.0 km buffer
    models = {}
    block_info = []
    buffer_km = 2.0
    for b in sorted(df_train["block_id"].unique()):
        te = (df_train["block_id"] == b).to_numpy()
        lo, hi = along_train[te].min(), along_train[te].max()
        tr = (~te) & ((along_train < lo - buffer_km) | (along_train > hi + buffer_km))
        m = RandomForestClassifier(n_estimators=400, min_samples_leaf=5, class_weight="balanced_subsample",
                                   random_state=42, n_jobs=-1)
        m.fit(X_train[tr], y_train[tr])
        models[b] = m
        p_te = m.predict_proba(X_train[te])[:, 1]
        b_auc = roc_auc_score(y_train[te], p_te)
        block_info.append({
            "block_id": b,
            "along_min": lo,
            "along_max": hi,
            "train_rows": int(tr.sum()),
            "test_rows": int(te.sum()),
            "block_auc": b_auc,
        })
        print(f"Block {b}: test along [{lo:.1f}, {hi:.1f}] km | train points: {tr.sum()}/{len(df_train)} | AUC: {b_auc:.3f}")

    # 3. Extract 30m DEM features for the deduplicated road points
    dedup_df = part1_res["dedup_df"]
    dem = F.load_dem_mosaic(None, None, cache_dir=DEM_CACHE_DIR)
    feats_list = [dem.features(r.latitude, r.longitude) for _, r in dedup_df.iterrows()]
    feats_df = pd.DataFrame(feats_list)

    # Project deduplicated points to coarse route to match training along_km coordinate frame
    bseg = S.load_backend_segments(None)
    verts = [(bseg.start_lat[0], bseg.start_lng[0])] + list(zip(bseg.end_lat, bseg.end_lng))
    proj = B.Proj(float(np.mean([v[0] for v in verts])))
    seg_csv = B.load_segments(SEGMENTS_CSV)
    coarse_xy = proj.xy(seg_csv["latitude"], seg_csv["longitude"])
    pts_xy = proj.xy(dedup_df.latitude, dedup_df.longitude)
    _, _, along_pts, _ = B.project_to_polyline(pts_xy, coarse_xy)

    # Determine which block covers each road point
    block_cutoffs = [0.0] + [df_train[df_train.block_id == b]["along_km"].max() for b in range(5)] + [1000.0]
    pt_blocks = np.clip(np.digitize(along_pts, block_cutoffs[1:-1]), 0, 5)

    # Score each point using its corresponding held-out model (honest OOF)
    p_oof = np.zeros(len(dedup_df))
    for b in range(6):
        idx = np.where(pt_blocks == b)[0]
        if len(idx) > 0:
            p_oof[idx] = models[b].predict_proba(feats_df.loc[idx, DEM_FEATURES].to_numpy(float))[:, 1]

    # Aggregate to segments: 90th percentile worst stretch
    seg_point_indices = part1_res["seg_point_indices"]
    oof_p90 = []
    oof_mean = []
    for cid in part1_res["seg_table"]["id"]:
        idx = seg_point_indices[cid]
        if len(idx) > 0:
            oof_p90.append(float(np.quantile(p_oof[idx], 0.90)))
            oof_mean.append(float(np.mean(p_oof[idx])))
        else:
            oof_p90.append(np.nan)
            oof_mean.append(np.nan)

    # 4. Load 309 inventory landslides and project to highway to find ground truth count per segment
    inv_df = pd.read_csv(INVENTORY_CSV)
    gdf_hw = gpd.read_file(GEOJSON_ROUTE).to_crs(epsg=32644)
    highway = gdf_hw.geometry.iloc[0]
    total_len_km = highway.length / 1000.0

    inv_gdf = gpd.GeoDataFrame(
        geometry=[Point(x, y) for x, y in zip(inv_df["longitude"], inv_df["latitude"])],
        crs="EPSG:4326",
    ).to_crs(epsg=32644)
    inv_along = np.array([highway.project(pt) / 1000.0 for pt in inv_gdf.geometry])

    observed_slides = []
    slides_per_km = []
    for i, row in part1_res["seg_table"].iterrows():
        ds, de, length = row["start_km"], row["end_km"], row["length_km"]
        in_seg = (inv_along >= ds) & (inv_along < de if de < total_len_km else inv_along <= de)
        n_s = int(in_seg.sum())
        observed_slides.append(n_s)
        slides_per_km.append(n_s / length if length > 0 else 0.0)

    # Build correlation dataframe
    corr_df = part1_res["seg_table"].copy()
    corr_df["observed_slides"] = observed_slides
    corr_df["slides_per_km"] = slides_per_km
    corr_df["oof_p90"] = oof_p90
    corr_df["oof_mean"] = oof_mean
    corr_df["obs_rank"] = pd.Series(slides_per_km).rank(ascending=False).astype(int)
    corr_df["model_rank"] = pd.Series(oof_p90).rank(ascending=False).astype(int)

    # Rank percentile among 18 segments
    corr_df["model_percentile"] = (rankdata(oof_p90) - 1) / (len(oof_p90) - 1)
    corr_df["obs_percentile"] = (rankdata(slides_per_km) - 1) / (len(slides_per_km) - 1)

    # Spearman rank correlation
    rho, pval = spearmanr(corr_df["oof_p90"], corr_df["slides_per_km"])
    print(f"\nSpearman correlation (OOF p90 vs slides/km): rho = {rho:.3f} (p-value = {pval:.4f})")

    # Inspect seg_08 and seg_09 specifically
    s08 = corr_df[corr_df.id == "seg_08"].iloc[0]
    s09 = corr_df[corr_df.id == "seg_09"].iloc[0]
    print(f"seg_08 (Srinagar to Sirobagarh): Observed = {s08['observed_slides']} slides ({s08['slides_per_km']:.2f}/km, rank #{s08['obs_rank']}/18) | OOF p90 = {s08['oof_p90']:.3f} (rank #{s08['model_rank']}/18)")
    print(f"seg_09 (Sirobagarh to Rudraprayag): Observed = {s09['observed_slides']} slides ({s09['slides_per_km']:.2f}/km, rank #{s09['obs_rank']}/18) | OOF p90 = {s09['oof_p90']:.3f} (rank #{s09['model_rank']}/18)")

    return {
        "rho": rho,
        "pval": pval,
        "corr_df": corr_df,
        "block_info": block_info,
        "seg_08": s08.to_dict(),
        "seg_09": s09.to_dict(),
    }


def part3_permutation_importance_and_bootstrap():
    """
    (3) Report permutation importance on held-out blocks and block-bootstrap 95%
    confidence intervals for pooled AUC and block AUC.
    """
    print("\n" + "=" * 70)
    print("PART 3: Held-out Permutation Importance & Block-Bootstrap 95% CIs")
    print("=" * 70)

    df = pd.read_csv(TRAIN_DATA_V2)
    along = df["along_km"].to_numpy()
    y = df["label"].to_numpy()
    X = df[DEM_FEATURES].to_numpy(float)

    # 1. Fit models and compute baseline predictions
    oof = np.zeros(len(df))
    models = {}
    base_block_aucs = {}
    for b in sorted(df["block_id"].unique()):
        te = (df["block_id"] == b).to_numpy()
        lo, hi = along[te].min(), along[te].max()
        tr = (~te) & ((along < lo - 2.0) | (along > hi + 2.0))
        m = RandomForestClassifier(n_estimators=400, min_samples_leaf=5, class_weight="balanced_subsample",
                                   random_state=42, n_jobs=-1)
        m.fit(X[tr], y[tr])
        models[b] = m
        p = m.predict_proba(X[te])[:, 1]
        oof[te] = p
        base_block_aucs[b] = roc_auc_score(y[te], p)

    base_pooled_auc = roc_auc_score(y, oof)
    base_block_mean = float(np.mean(list(base_block_aucs.values())))
    base_block_std = float(np.std(list(base_block_aucs.values())))

    print(f"Baseline OOF: Pooled AUC = {base_pooled_auc:.4f} | Block AUC Mean = {base_block_mean:.4f} +- {base_block_std:.4f}")

    # 2. Permutation importance on held-out blocks
    # We evaluate on the held-out test sets across multiple repeats
    rng = np.random.default_rng(42)
    n_repeats = 10
    perm_records = []

    for j, col in enumerate(DEM_FEATURES):
        drops_pooled = []
        drops_block = []
        for _ in range(n_repeats):
            oof_perm = np.zeros(len(df))
            block_aucs_perm = []
            for b in sorted(df["block_id"].unique()):
                te = (df["block_id"] == b).to_numpy()
                X_te = X[te].copy()
                X_te[:, j] = rng.permutation(X_te[:, j])
                p_perm = models[b].predict_proba(X_te)[:, 1]
                oof_perm[te] = p_perm
                block_aucs_perm.append(roc_auc_score(y[te], p_perm))
            drops_pooled.append(base_pooled_auc - roc_auc_score(y, oof_perm))
            drops_block.append(base_block_mean - float(np.mean(block_aucs_perm)))

        perm_records.append({
            "feature": col,
            "drop_pooled_auc_mean": float(np.mean(drops_pooled)),
            "drop_pooled_auc_std": float(np.std(drops_pooled)),
            "drop_block_auc_mean": float(np.mean(drops_block)),
            "drop_block_auc_std": float(np.std(drops_block)),
        })

    perm_df = pd.DataFrame(perm_records).sort_values("drop_pooled_auc_mean", ascending=False).reset_index(drop=True)
    print("\nPermutation Importance on Held-out Blocks:")
    for _, r in perm_df.iterrows():
        print(f"  {r['feature']:20s} | drop pooled AUC: {r['drop_pooled_auc_mean']:+.4f} (+-{r['drop_pooled_auc_std']:.4f}) | drop block AUC: {r['drop_block_auc_mean']:+.4f}")

    # 3. Block-Bootstrap 95% Confidence Intervals (B=1000)
    n_boot = 1000
    boot_pooled = []
    boot_block = []
    blocks = sorted(df["block_id"].unique())
    block_auc_arr = np.array([base_block_aucs[b] for b in blocks])

    for _ in range(n_boot):
        sampled_blocks = rng.choice(blocks, size=len(blocks), replace=True)
        # Sampled observations for pooled calculation
        idxs = np.concatenate([np.where(df["block_id"] == sb)[0] for sb in sampled_blocks])
        if len(np.unique(y[idxs])) == 2:
            boot_pooled.append(roc_auc_score(y[idxs], oof[idxs]))
        # Mean across the sampled blocks
        boot_block.append(float(np.mean([base_block_aucs[sb] for sb in sampled_blocks])))

    ci_pooled = np.percentile(boot_pooled, [2.5, 97.5])
    ci_block = np.percentile(boot_block, [2.5, 97.5])

    print(f"\nBlock-Bootstrap 95% Confidence Intervals (B={n_boot}):")
    print(f"  Pooled AUC:     {base_pooled_auc:.3f}  [95% CI: {ci_pooled[0]:.3f} - {ci_pooled[1]:.3f}]")
    print(f"  Block AUC Mean: {base_block_mean:.3f}  [95% CI: {ci_block[0]:.3f} - {ci_block[1]:.3f}]")

    return {
        "base_pooled_auc": base_pooled_auc,
        "base_block_mean": base_block_mean,
        "base_block_std": base_block_std,
        "perm_df": perm_df,
        "ci_pooled": ci_pooled.tolist(),
        "ci_block": ci_block.tolist(),
        "base_block_aucs": base_block_aucs,
    }


def part4_negative_separation_sensitivity():
    """
    (4) Rerun the headline model with minimum negative separation of 100 m, 250 m and 500 m.
    """
    print("\n" + "=" * 70)
    print("PART 4: Sensitivity to Negative Separation Distance (100 m, 250 m, 500 m)")
    print("=" * 70)

    inv_full = B.load_inventory(INVENTORY_CSV)
    seg = B.load_segments(SEGMENTS_CSV)
    proj = B.Proj(float(inv_full["latitude"].mean()))
    coarse_xy = proj.xy(seg["latitude"], seg["longitude"])
    pos_xy = proj.xy(inv_full["latitude"], inv_full["longitude"])
    d_c, _, along_c, _ = B.project_to_polyline(pos_xy, coarse_xy)
    a_min, a_max = float(along_c.min()), float(along_c.max())

    cache = json.loads(Path(B.ROAD_CACHE_FILE).read_text(encoding="utf-8"))
    ways = [[tuple(p) for p in w] for w in cache.get("ways", [])]
    pts25, _ = B.densify_polyline_ways(ways, proj, 0.025)
    tree25 = cKDTree(pts25)
    d_osm, _ = tree25.query(pos_xy)

    pool_pts, pool_tans = B.densify_polyline_ways(ways, proj, 0.10)
    dpool, _, apool, _ = B.project_to_polyline(pool_pts, coarse_xy)
    keep = (apool >= a_min - 1.0) & (apool <= a_max + 1.0) & (dpool <= 12.0)
    ref_pool_pts, ref_pool_tans = pool_pts[keep], pool_tans[keep]
    ref_tree = tree25
    offsets = d_osm

    dem = F.load_dem_mosaic(None, None, cache_dir=DEM_CACHE_DIR)
    pos_feats = [dem.features(r.latitude, r.longitude) for _, r in inv_full.iterrows()]
    pos_df = pd.DataFrame(pos_feats)
    pos_df["label"] = 1
    pos_df["along_km"] = along_c
    pos_df["dist_ref_km"] = d_osm

    results = {}
    for sep_m in [100, 250, 500]:
        rng = np.random.default_rng(42)
        n_target = int(round(3.0 * len(inv_full)))
        neg_xy = B.sample_negatives(ref_pool_pts, ref_pool_tans, offsets, pos_xy, n_target,
                                    sep_m / 1000.0, rng, ref_tree)
        nlat, nlon = proj.latlon(neg_xy)
        _, _, along_neg, _ = B.project_to_polyline(neg_xy, coarse_xy)
        d_neg = ref_tree.query(neg_xy)[0]

        neg_feats = [dem.features(la, lo) for la, lo in zip(nlat, nlon)]
        neg_df = pd.DataFrame(neg_feats)
        neg_df["label"] = 0
        neg_df["along_km"] = along_neg
        neg_df["dist_ref_km"] = d_neg

        full_df = pd.concat([pos_df, neg_df], ignore_index=True)
        full_df["block_id"] = pd.qcut(full_df["along_km"], q=6, labels=False, duplicates="drop").astype(int)

        # Leak check
        leak_auc, l_lo, l_hi = B.univariate_auc_ci(full_df["dist_ref_km"].abs().to_numpy(), full_df["label"].to_numpy())

        # Spatial-block CV
        along = full_df["along_km"].to_numpy()
        y = full_df["label"].to_numpy()
        X = full_df[DEM_FEATURES].to_numpy(float)
        oof = np.zeros(len(full_df))
        block_aucs = []

        for b in sorted(full_df["block_id"].unique()):
            te = (full_df["block_id"] == b).to_numpy()
            lo, hi = along[te].min(), along[te].max()
            tr = (~te) & ((along < lo - 2.0) | (along > hi + 2.0))
            m = RandomForestClassifier(n_estimators=400, min_samples_leaf=5, class_weight="balanced_subsample",
                                       random_state=42, n_jobs=-1)
            m.fit(X[tr], y[tr])
            p = m.predict_proba(X[te])[:, 1]
            oof[te] = p
            block_aucs.append(float(roc_auc_score(y[te], p)))

        p_auc = float(roc_auc_score(y, oof))
        p_ap = float(average_precision_score(y, oof))
        thr = np.quantile(oof, 0.80)
        top20 = float((oof[y == 1] >= thr).mean())

        results[sep_m] = {
            "sep_m": sep_m,
            "target_neg": n_target,
            "placed_neg": len(neg_xy),
            "pool_exhausted": len(neg_xy) < n_target,
            "leak_auc": leak_auc,
            "leak_ci": [l_lo, l_hi],
            "pooled_auc": p_auc,
            "pooled_ap": p_ap,
            "top20_capture": top20,
            "block_auc_mean": float(np.mean(block_aucs)),
            "block_auc_std": float(np.std(block_aucs)),
            "block_aucs": block_aucs,
        }
        print(f"Separation {sep_m:3d} m: placed {len(neg_xy)}/{n_target} negatives | Leak AUC {leak_auc:.3f} | Pooled AUC {p_auc:.3f} | AP {p_ap:.3f} | Top20% {top20*100:.1f}%")

    return results


def part5_check_main_drivers():
    """
    (5) Check that every main_driver string in segment_static_scores.json is
    generated by score_segments.py and not hand-edited.
    """
    print("\n" + "=" * 70)
    print("PART 5: Audit of main_driver Strings in segment_static_scores.json")
    print("=" * 70)

    bundle = joblib.load(MODEL_V2_JOBLIB)
    cols = bundle["feature_columns"]
    imp = bundle["feature_importance"]
    saved_scores = json.loads(Path(SCORES_JSON).read_text(encoding="utf-8"))

    # Re-run score_segments logic
    bseg = S.load_backend_segments(None)
    verts = [(bseg.start_lat[0], bseg.start_lng[0])] + list(zip(bseg.end_lat, bseg.end_lng))
    proj = B.Proj(float(np.mean([v[0] for v in verts])))
    route_xy = proj.xy([v[0] for v in verts], [v[1] for v in verts])
    _, _, _, total = B.project_to_polyline(route_xy[:1], route_xy)
    cum = np.concatenate([[0.0], np.cumsum(np.hypot(*np.diff(route_xy, axis=0).T))])

    pts_xy, _ = S.road_points(proj, route_xy, 0.0, total, 0.25)
    _, _, along0, _ = B.project_to_polyline(pts_xy, route_xy)
    seg_idx = np.clip(np.searchsorted(cum[1:], along0, side="left"), 0, len(bseg) - 1)

    lat, lon = proj.latlon(pts_xy)
    pts = pd.DataFrame({"latitude": lat, "longitude": lon})
    dem = F.load_dem_mosaic(None, None, cache_dir=DEM_CACHE_DIR)
    feats_list = [dem.features(r.latitude, r.longitude) for _, r in pts.iterrows()]
    feats = pd.DataFrame(feats_list)

    ok = feats.notna().all(axis=1).to_numpy()
    feats, seg_idx = feats[ok].reset_index(drop=True), seg_idx[ok]
    mu, sd = feats[cols].mean(), feats[cols].std().replace(0, 1)

    audit_records = []
    discrepancies = []
    for i, s in bseg.iterrows():
        m = seg_idx == i
        z = (feats.loc[m, cols].mean() - mu) / sd
        contrib = {c: abs(imp.get(c, 0.0)) * abs(z[c]) for c in cols}
        top = max(contrib, key=contrib.get)
        direction = "high" if z[top] > 0 else "low"
        computed_driver = f"unusual {S.pretty(top)} for this road ({direction}, z={z[top]:+.1f})"
        saved_driver = saved_scores[i]["driver"]

        matches = (computed_driver == saved_driver)
        if not matches:
            discrepancies.append((s["id"], saved_driver, computed_driver))

        audit_records.append({
            "id": s["id"],
            "name": s["name"],
            "top_feature": top,
            "pretty_feature": S.pretty(top),
            "z_score": float(z[top]),
            "direction": direction,
            "computed_driver": computed_driver,
            "saved_driver": saved_driver,
            "matches": matches,
        })
        print(f"  {s['id']}: match={matches:1d} | '{saved_driver}'")

    print(f"\nAudit complete: {len(saved_scores) - len(discrepancies)}/18 strings match exactly.")
    if discrepancies:
        print("Discrepancies found:")
        for sid, sv, cp in discrepancies:
            print(f"  {sid}: saved='{sv}' != computed='{cp}'")
    else:
        print("VERIFIED: 100% of driver strings match the mathematical formulation in score_segments.py.")

    return {
        "discrepancies": discrepancies,
        "audit_df": pd.DataFrame(audit_records),
    }


